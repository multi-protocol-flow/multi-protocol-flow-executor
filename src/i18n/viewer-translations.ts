// ============================================================================
// Hook
// ============================================================================
export function useVT() {
  const locale = useSettingsStore((s) => s.locale) ?? 'zh-CN';
  const dict = locale.startsWith('en') ? en : zh;

  return (key: string, params?: TranslateParams): string => {
    let text = dict[key] ?? key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        if (v !== undefined) {
          text = text.replace(`{${k}}`, String(v));
        }
      });
    }
    return text;
  };
}